"""Run the two-session demo against the REAL LLM and print it as Markdown.

Run from backend/ (needs LLM_API_KEY in backend/.env):
    uv run python -m scripts.demo_two_sessions > ../docs/demo/DEMO.md

It uses a throw-away database, so your own data is untouched. Real model output varies.
"""

import sys
import tempfile
import time
from pathlib import Path

from fastapi.testclient import TestClient

from app.config import Settings
from app.main import create_app

PAUSE_SECONDS = 10  # stays under the free tier's tokens-per-minute limit

SESSIONS = [
    [
        "I think 1/2 + 1/3 = 2/5. You just add the tops and the bottoms.",
        "Oh, 2/5 is smaller than 1/2, so that can't be right. I don't know the right way though.",
    ],
    ["Last time I added the tops and bottoms. Now: 1/2 is 3/6 and 1/3 is 2/6, so it's 5/6!"],
]


def check(response) -> dict:
    if response.status_code >= 400:
        raise SystemExit(f"Request failed with {response.status_code}: {response.text}")
    return response.json()


def run_session(client: TestClient, base: str, number: int, learner_messages: list[str]) -> None:
    print(f"## Session {number}: Adding fractions\n")
    session = check(client.post(f"{base}/sessions", json={"topic": "Adding fractions"}))
    print(f"**Tutor:** {session['messages'][0]['content']}\n")
    url = f"{base}/sessions/{session['id']}"
    for text in learner_messages:
        time.sleep(PAUSE_SECONDS)
        turn = check(client.post(f"{url}/messages", json={"content": text}))
        print(f"**Alex:** {text}\n\n**Tutor:** {turn['tutor_message']['content']}\n")
    time.sleep(PAUSE_SECONDS)
    update = check(client.post(f"{url}/end"))["memory_update"]
    print("**Session ended. What the tutor learned:**\n")
    for change in ("created", "updated", "archived"):
        for memory in update[change]:
            print(f"- {change}: ({memory['kind']}) {memory['content']}")
    print()
    time.sleep(PAUSE_SECONDS)


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")  # the Windows console can't print every character
    database = Path(tempfile.mkdtemp()) / "demo.db"
    with TestClient(create_app(Settings(database_path=database))) as client:
        learner = check(client.post("/api/learners", json={"name": "Alex"}))
        base = f"/api/learners/{learner['id']}"
        print("# Demo: a first session and a return visit\n")
        print("Generated by `backend/scripts/demo_two_sessions.py` against the real model.\n")
        for number, learner_messages in enumerate(SESSIONS, start=1):
            run_session(client, base, number, learner_messages)
        print("## Memory after both sessions\n")
        for memory in check(client.get(f"{base}/memories")):
            print(f"- ({memory['kind']}, {memory['status']}) {memory['content']}")


if __name__ == "__main__":
    main()
